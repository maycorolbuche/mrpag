import ejs from 'ejs';
import { mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
await mkdir('src/generated', { recursive: true });
const names = ['auth', 'header', 'password', 'dashboard', 'account', 'customers', 'customer-form', 'customer-detail', 'payment-settings', 'payment-authorize', 'charges', 'charge-form', 'charge-detail'];
const compiled = await Promise.all(names.map(async name => {
  const source = await readFile(`views/${name}.ejs`, 'utf8');
  const fn = ejs.compile(source, { client: true, _with: false, destructuredLocals: ['page','csrf','user','error','success','email','resetToken','title','account','currentPath','saved','customers','filters','pagination','customer','errors','editing','integration','formId','endpoint','activeEndpoint','oauthReady','oauthConnect','manualError','authorizationUrl','charges','chargePage','nextPage','chargeFields','charge'], compileDebug: false, filename: `${name}.ejs` }).toString();
  return `${JSON.stringify(name)}: ${fn}`;
}));
await writeFile('src/generated/templates.js', `// Generated by scripts/build.mjs; no runtime eval or filesystem access.\nconst templates = {${compiled.join(',\n')}};\nexport function render(name, data) { return templates[name](data, undefined, (partial, extra = {}) => render(partial, {...data, ...extra})); }\n`);
await rm('dist', { recursive: true, force: true });
await mkdir('dist/assets/bootstrap', { recursive: true });
await cp('public', 'dist/assets', { recursive: true });
await cp('node_modules/bootstrap/dist/css/bootstrap.min.css', 'dist/assets/bootstrap/bootstrap.min.css');
console.log('Templates e assets preparados para o Worker.');

await writeFile('dist/_headers', '/assets/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: no-referrer\n');
